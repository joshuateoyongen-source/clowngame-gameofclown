self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);

    // Cache the main app files first so the basic game shell is available.
    for (const path of APP_SHELL) {
      try {
        const url = new URL(path, self.registration.scope);
        const response = await fetch(url, { cache: "reload" });
        if (!response.ok) throw new Error(`HTTP ${response.status}`);
        await cache.put(url, response.clone());
      } catch (error) {
        console.error("[Clown Game] Could not cache app-shell file:", path, error);
        throw error;
      }
    }

    // Cache assets in small batches to avoid launching 1,300+ requests at once.
    // A failed asset is reported, while the rest of the game continues caching.
    const batchSize = 20;
    const failedAssets = [];

    for (let i = 0; i < ASSETS_TO_CACHE.length; i += batchSize) {
      const batch = ASSETS_TO_CACHE.slice(i, i + batchSize);
      await Promise.all(batch.map(async (path) => {
        try {
          const url = new URL(path, self.registration.scope);
          const response = await fetch(url, { cache: "reload" });
          if (!response.ok) throw new Error(`HTTP ${response.status}`);
          await cache.put(url, response.clone());
        } catch (error) {
          failedAssets.push(path);
          console.warn("[Clown Game] Asset was not cached:", path, error);
        }
      }));
    }

    if (failedAssets.length) {
      console.error(
        `[Clown Game] Offline setup finished with ${failedAssets.length} uncached asset(s). ` +
        "Check the browser console for their paths."
      );
    } else {
      console.log(`[Clown Game] Offline cache ready: ${ASSETS_TO_CACHE.length} assets cached.`);
    }

    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const cacheNames = await caches.keys();
    await Promise.all(cacheNames
      .filter((name) => name.startsWith("clown-game-offline-") && name !== CACHE_NAME)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const requestUrl = new URL(request.url);
  const scopeUrl = new URL(self.registration.scope);

  // Only handle requests belonging to this GitHub Pages app.
  if (requestUrl.origin !== scopeUrl.origin ||
      !requestUrl.pathname.startsWith(scopeUrl.pathname)) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(request);
    if (cached) return cached;

    try {
      const response = await fetch(request);
      if (response.ok) {
        await cache.put(request, response.clone());
      }
      return response;
    } catch (error) {
      // If the browser navigates while offline, show the cached app homepage.
      if (request.mode === "navigate") {
        const home = await cache.match(new URL("./index.html", self.registration.scope));
        if (home) return home;
      }
      throw error;
    }
  })());
});
